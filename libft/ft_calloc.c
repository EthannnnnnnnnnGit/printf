#include "libft.h"

void	*ft_calloc(size_t nmemb, size_t size)
{
	int		buff;
	void	*p;

	if (nmemb == 0 || size == 0)
		return (malloc(0));
	buff = nmemb * size;
	if (buff / size != nmemb)
		return (NULL);
	p = malloc(nmemb * size);
	if (!p)
		return (NULL);
	ft_bzero(p, nmemb * size);
	return (p);
}
